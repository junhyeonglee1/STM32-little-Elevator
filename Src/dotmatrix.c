void dotmatrix_test(void)
{
	for (int i=0; i < 8; i++)
	{
		// 공통 양극 방식
		// column에는 0을 ROW에는 1을 출력해야 해당 LED가 on된다.
		col[0] = ~(1 << i);  // 00000001 -> 11111110
		col[1] = number_data[current_floor][i];
		HAL_SPI_Transmit(&hspi2, col, 2, 1);
		GPIOB->ODR &= ~GPIO_PIN_15;   // latch핀을 pull-down
		GPIOB->ODR |= GPIO_PIN_15;   // latch핀을 pull-up
		HAL_Delay(1);
	}
}



void elevator_dotmatrix(void)
{
	switch(stepmotor_state)
	{
	case RUN:
		if(step_motor_direction == FORWARD)
		{
			memcpy(elevator_display_data[0], number_data_1[current_floor+1], sizeof(number_data_1[current_floor]));
			memcpy(elevator_display_data[1], direction_data[0], sizeof(direction_data[0]));
			dotmatrix_main();
		}
		else if(step_motor_direction == REVERSE)
		{
			memcpy(elevator_display_data[0], number_data_1[current_floor-1], sizeof(number_data_1[current_floor]));
			memcpy(elevator_display_data[1], direction_data[1], sizeof(direction_data[1]));
			dotmatrix_main1();
		}
		break;
	case STOP:
		dotmatrix_print_main();
		break;
	}

}


void make_dot(char *str)
{
	char buff[10];

	strcpy(buff,str);

	int buff_index;

	for(int i=0;i<strlen(str);i++)
	{
		if(buff[i]>='0' && buff[i]<= '9') //숫자입력받으면 숫자버퍼에서 갖고오기
		{
			buff_index = buff[i]-'0'; //ASCII to INT
			memcpy(recieved_data[i], number_data[buff_index], sizeof(number_data[buff_index])); // number버퍼 배열을 출력할 배열에 대입
		}
		else if(buff[i] >= 'a' && buff[i] <= 'z')
		{
			buff_index = buff[i] - 'a'; //ASCII to INT
			memcpy(recieved_data[i], lower_alphabet_data[buff_index], sizeof(lower_alphabet_data[buff_index]));// 알파벳버퍼 배열을 출력할 배열에 대입
		}
		else if(buff[i] >= 'A' && buff[i] <= 'Z')
		{
			buff_index = buff[i] - 'A'; //ASCII to INT
			memcpy(recieved_data[i], upper_alphabet_data[buff_index], sizeof(upper_alphabet_data[buff_index]));// 알파벳버퍼 배열을 출력할 배열에 대입
		}
		else if(buff[i]=='\0')
		{
			break;
		}
	}
	dotmatrix_main();
}

