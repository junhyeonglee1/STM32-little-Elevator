// 1. display_data에 number_data[0]에 있는 내용 복사
// 2. number_data를 scroll_buffer에 복사
// 3. dotmatrix의 led를 off
void init_dotmatrix(void)
{
	for (int i=0; i < 8; i++)
	{
		display_data[i] = elevator_display_data[i];
	}
	for (int i=1; i < number_of_character+1; i++)
	{
		for (int j=0; j < 8; j++) // scroll_buffer[0] = blank
		{
			scroll_buffer[i][j] = elevator_display_data[i-1][j];
		}
	}
}
char prev_stepmotor_state = 0;
int prev_stop_flag = 0;
int prev_floor = 1;

void dotmatrix_print_main(void)
{
	while (prev_stepmotor_state == stepmotor_state && prev_stop_flag == stop_flag && prev_floor == current_floor)
	{
		for (int i=0; i < 8; i++)
		{
			col[0] = ~(1 << i);
			col[1] = number_data_1[current_floor][i];
			HAL_SPI_Transmit(&hspi2, col, 2, 1); // 2byte 전송
			GPIOB->ODR &= ~GPIO_PIN_15;          // latch핀을 pull-down
			GPIOB->ODR |= GPIO_PIN_15;           // latch핀을 pull-up
			HAL_Delay(1);  // 잔상 없애기 위해
		}
	}
	prev_stepmotor_state = stepmotor_state;
	prev_stop_flag = stop_flag;
	prev_floor = current_floor;
}

